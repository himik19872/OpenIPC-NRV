-- Фильтры точности детекции.
--
-- Причина: на реальной системе за сутки набегало 475 событий по лицам при
-- 104 событиях по людям, и 261 по котам. Источников шума было несколько:
-- низкий порог уверенности (0.4), отсутствие проверки размера объекта и
-- запуск распознавания лиц на кадрах, где человека могло не быть вовсе.
--
-- Часть настроек задаётся на камеру отдельно: у обзорной камеры во дворе и
-- у камеры на проходной требования к размеру объекта разные.

ALTER TABLE detection_settings
    -- Минимальная площадь объекта в долях от площади кадра (0..1).
    -- Отсекает мелкие ложные рамки, которые YOLO ставит на шум, блики и
    -- фрагменты текстур.
    --
    -- Значение 0.004 (0,4%) подобрано по замеру на реальных камерах с
    -- субпотоком 704x576: человек вдали занимает около 1,7% кадра, а шум и
    -- мелкие блики — меньше 0,3%. Порог 2% отсекал бы реальных людей.
    ADD COLUMN IF NOT EXISTS min_object_area real NOT NULL DEFAULT 0.004,

    -- Максимальная площадь объекта в долях от площади кадра.
    -- Защита от обратной ошибки: когда камера «видит» весь кадр как один
    -- объект (смена освещения, запотевание, закрытая шторка).
    -- 1 означает отсутствие ограничения.
    ADD COLUMN IF NOT EXISTS max_object_area real NOT NULL DEFAULT 0.9,

    -- Соотношение сторон рамки: максимальное отношение длинной стороны к
    -- короткой. Настоящие объекты COCO укладываются в 5:1; более вытянутые
    -- рамки — это тени, столбы, отражения и щели.
    -- 0 означает отсутствие проверки.
    ADD COLUMN IF NOT EXISTS max_aspect_ratio real NOT NULL DEFAULT 5.0,

    -- Сколько секунд объект должен оставаться малоподвижным, чтобы его
    -- перестали считать целью. Стул, тень или забытая коробка не должны
    -- давать событие каждые несколько секунд.
    -- 0 отключает проверку.
    ADD COLUMN IF NOT EXISTS static_seconds real NOT NULL DEFAULT 0,

    -- Порог уверенности, при котором кадр считается пригодным для
    -- распознавания лиц. Ниже этого значения распознавание не запускается,
    -- даже если лица включены в detect_types.
    ADD COLUMN IF NOT EXISTS face_min_confidence real NOT NULL DEFAULT 0.6,

    -- Требовать ли наличия человека в кадре перед распознаванием лиц.
    -- Основной источник шума был именно здесь: распознавание запускалось
    -- на любом кадре, и модель находила «лица» в текстурах.
    ADD COLUMN IF NOT EXISTS face_requires_person boolean NOT NULL DEFAULT true;

-- Поднимаем порог уверенности по умолчанию с 0.4 до 0.6.
-- 0.4 — слишком низкое значение для YOLOv8: через него проходит шум и
-- ложные рамки. Влияет только на новые записи, существующие не меняем.
ALTER TABLE detection_settings
    ALTER COLUMN min_confidence SET DEFAULT 0.6;

-- Обновляем только те камеры, где стоит прежнее значение по умолчанию.
-- Камеры с осознанно подобранным порогом (0.85, 0.9, 0.25, 0.3) не трогаем.
--
-- Приведение ::real обязательно: колонка объявлена как real (4 байта), а
-- литерал 0.4 в SQL — это numeric, и сравнение real = numeric даёт false
-- при внешне равных значениях. Без приведения UPDATE находит 0 строк.
UPDATE detection_settings
   SET min_confidence = 0.6::real
 WHERE min_confidence = 0.4::real;

-- Индекс нужен детектору: он раз в 10 секунд читает включённые камеры.
CREATE INDEX IF NOT EXISTS idx_detection_settings_filters
    ON detection_settings (enabled)
    WHERE enabled = true;
